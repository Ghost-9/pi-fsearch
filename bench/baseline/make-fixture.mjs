// bench/baseline/make-fixture.mjs
// Deterministic ~5k-file fixture for UltraSearch baselines.
// Idempotent: skips regeneration when the complete fixture is present.
//   node bench/baseline/make-fixture.mjs [--force]
//
// Layout:
//   <root>/dir_00..dir_49/module_00000.ts .. module_04999.ts   (5000 files)
//   <root>/dir_00/mod_special_alpha.ts
//   <root>/deep/nested/level1/level2/level3/deep_nested_file.ts
//   <root>/dir_{00,25,49}/package.json
//
// Every i%7==0 file contains ULTRAMARKER_<i>; every i%13==0 file contains
// special_alpha_marker. Content is derived only from the index -> deterministic.

import * as fs from "node:fs";
import * as path from "node:path";
import {
  FIXTURE_ROOT,
  FIXTURE_SPECIAL,
  ensureTestEnv,
  utcDate,
} from "./lib.mjs";

ensureTestEnv();

const force = process.argv.includes("--force");
const NATIVE_CANDIDATES = 5000;

function fileContent(i) {
  const lines = [];
  lines.push(`// module_${String(i).padStart(5, "0")}.ts — deterministic fixture file`);
  lines.push(`// generated by bench/baseline/make-fixture.mjs (wave1/baseline)`);
  for (let k = 0; k < 30; k++) {
    lines.push(`export const value_${i}_${k} = ${(i * 31 + k * 7) % 100000}; // payload line ${k}`);
  }
  if (i % 7 === 0) {
    lines.push(`export const marker_${i} = "${FIXTURE_SPECIAL.marker.replace("1232", String(i))}";`);
  }
  if (i % 13 === 0) {
    lines.push(`export const alpha_${i} = "special_alpha_marker";`);
  }
  lines.push(`export type ModuleType${i} = { id: ${i}; name: string };`);
  return lines.join("\n") + "\n";
}

function specialFileContent() {
  return [
    "// mod_special_alpha.ts — fixture special case",
    'export const alpha = "special_alpha_marker";',
    `export const alias = "${FIXTURE_SPECIAL.marker.toLowerCase()}";`,
    'export const note = "one-off file outside the numbered modules";',
  ].join("\n") + "\n";
}

function deepFileContent() {
  return [
    "// deep_nested_file.ts — fixture deep path case",
    'export const depth = "level3";',
    'export const note = "nested deep inside the fixture";',
  ].join("\n") + "\n";
}

function packageJsonContent(d) {
  return JSON.stringify(
    { name: `fixture-pkg-${d}`, version: "1.0.0", private: true, fixture: true },
    null,
    2,
  ) + "\n";
}

function expectedTotal() {
  return NATIVE_CANDIDATES + 1 + 1 + 3;
}

function currentCount() {
  if (!fs.existsSync(FIXTURE_ROOT)) return 0;
  let n = 0;
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(p);
      else n++;
    }
  };
  walk(FIXTURE_ROOT);
  return n;
}

const t0 = Date.now();
if (!force && currentCount() === expectedTotal()) {
  console.log(
    JSON.stringify({ root: FIXTURE_ROOT, files: expectedTotal(), skipped: true, tookMs: Date.now() - t0 }),
  );
  process.exit(0);
}

fs.rmSync(FIXTURE_ROOT, { recursive: true, force: true });
let written = 0;

for (let d = 0; d < 50; d++) {
  const dir = path.join(FIXTURE_ROOT, `dir_${String(d).padStart(2, "0")}`);
  fs.mkdirSync(dir, { recursive: true });
  for (let k = 0; k < 100; k++) {
    const i = d * 100 + k;
    fs.writeFileSync(path.join(dir, `module_${String(i).padStart(5, "0")}.ts`), fileContent(i));
    written++;
  }
}

fs.writeFileSync(path.join(FIXTURE_ROOT, "dir_00", "mod_special_alpha.ts"), specialFileContent());
written++;
for (const d of ["00", "25", "49"]) {
  fs.writeFileSync(path.join(FIXTURE_ROOT, `dir_${d}`, "package.json"), packageJsonContent(d));
  written++;
}
const deepDir = path.join(FIXTURE_ROOT, "deep", "nested", "level1", "level2", "level3");
fs.mkdirSync(deepDir, { recursive: true });
fs.writeFileSync(path.join(deepDir, "deep_nested_file.ts"), deepFileContent());
written++;

console.log(
  JSON.stringify({
    root: FIXTURE_ROOT,
    files: written,
    skipped: false,
    tookMs: Date.now() - t0,
    generated_at: utcDate(),
  }),
);
